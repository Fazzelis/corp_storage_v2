from fastapi import FastAPI

from core.exceptions.auth_exceptions import (
    UserAlreadyRegistered,
    InvalidLoginOrPassword,
    RefreshTokenNotFound,
    InvalidRecoveryCode,
    InvalidTicket,
    TooManyAttempts,
    TooSoonToResendCode
)
from core.exceptions.jwt_exceptions import (
    JwtTypeNotFoundException,
    ExpiredTokenException,
    WrongTokenTypeException,
    TokenDecodeException
)
from core.exceptions.user_exceptions import (
    UserNotFound,
    UserMustChangePassword
)
from core.exceptions.avatar_exceptions import (
    EmptyAvatarException,
    UnsupportedAvatarTypeException,
    TooBigResolutionAvatarException,
    TooSmallResolutionAvatarException,
    NotImageAvatarException,
    TooBigFileSizeAvatarException,
    FailToWriteAvatarException,
    ImageNotFoundAvatarException
)
from api.exceptions.exception_handler import ExceptionHandler


def registrate_all_exceptions(app: FastAPI):
    app.add_exception_handler(
        UserAlreadyRegistered,
        ExceptionHandler.user_already_exist_handler
    )
    app.add_exception_handler(
        InvalidLoginOrPassword,
        ExceptionHandler.invalid_login_or_password_handler
    )
    app.add_exception_handler(
        RefreshTokenNotFound,
        ExceptionHandler.refresh_token_not_found_handler
    )
    app.add_exception_handler(
        InvalidRecoveryCode,
        ExceptionHandler.invalid_recover_code_handler
    )
    app.add_exception_handler(
        InvalidTicket,
        ExceptionHandler.invalid_ticket_handler
    )
    app.add_exception_handler(
        JwtTypeNotFoundException,
        ExceptionHandler.jwt_type_not_found_handler
    )
    app.add_exception_handler(
        ExpiredTokenException,
        ExceptionHandler.expired_token_handler
    )
    app.add_exception_handler(
        WrongTokenTypeException,
        ExceptionHandler.wrong_token_type_handler
    )
    app.add_exception_handler(
        TokenDecodeException,
        ExceptionHandler.token_decode_exception_handler
    )
    app.add_exception_handler(
        UserNotFound,
        ExceptionHandler.user_not_found_exception_handler
    )
    app.add_exception_handler(
        UserMustChangePassword,
        ExceptionHandler.user_must_change_password_exception_handler
    )
    app.add_exception_handler(
        EmptyAvatarException,
        ExceptionHandler.empty_avatar_exception_handler
    )
    app.add_exception_handler(
        UnsupportedAvatarTypeException,
        ExceptionHandler.unsupported_avatar_type_exception_handler
    )
    app.add_exception_handler(
        TooBigResolutionAvatarException,
        ExceptionHandler.too_big_resolution_avatar_exception_handler
    )
    app.add_exception_handler(
        TooSmallResolutionAvatarException,
        ExceptionHandler.too_small_resolution_avatar_exception_handler
    )
    app.add_exception_handler(
        NotImageAvatarException,
        ExceptionHandler.not_a_image_avatar_exception_handler
    )
    app.add_exception_handler(
        TooBigFileSizeAvatarException,
        ExceptionHandler.too_big_file_size_avatar_exception_handler
    )
    app.add_exception_handler(
        FailToWriteAvatarException,
        ExceptionHandler.fail_to_write_avatar_exception_handler
    )
    app.add_exception_handler(
        ImageNotFoundAvatarException,
        ExceptionHandler.image_not_found_avatar_exception_handler
    )
    app.add_exception_handler(
        TooManyAttempts,
        ExceptionHandler.too_many_attempts_recovery_code_exception_handler
    )
    app.add_exception_handler(
        TooSoonToResendCode,
        ExceptionHandler.too_soon_to_resend_code_exception_handler
    )
